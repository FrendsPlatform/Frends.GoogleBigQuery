using Frends.GoogleBigQuery.DeleteResource.Definitions;
using Frends.GoogleBigQuery.DeleteResource.Helpers;
using Google.Apis.Auth.OAuth2;
using Google.Apis.Bigquery.v2;
using Google.Apis.Services;
using System;
using System.ComponentModel;
using System.IO;
using System.Threading;
using System.Threading.Tasks;

namespace Frends.GoogleBigQuery.DeleteResource;

/// <summary>
/// Google BigQuery Task.
/// </summary>
public static class GoogleBigQuery
{
    /// <summary>
    /// Delete resource.
    /// [Documentation](https://tasks.frends.com/tasks/frends-tasks/Frends.GoogleBigQuery.DeleteResource)
    /// </summary>
    /// <param name="input">Input parameters.</param>
    /// <param name="connection">Connection parameters.</param>
    /// <param name="options">Optional parameters.</param>
    /// <param name="cancellationToken">Token generated by Frends to stop this Task.</param>
    /// <returns>Object { bool Success, Object Error { string Message, Exception AdditionalInfo } }</returns>
    public static async Task<Result> DeleteResource([PropertyTab] Input input, [PropertyTab] Connection connection, [PropertyTab] Options options, CancellationToken cancellationToken)
    {
        try
        {
            var serviceInitializer = new BaseClientService.Initializer
            {
                HttpClientInitializer = await GetServiceAccountCredential(connection, cancellationToken),
                ApplicationName = "BigQueryApp",
                BaseUri = string.IsNullOrWhiteSpace(connection.BaseUri) ? null : connection.BaseUri,
            };
            var bigqueryService = new BigqueryService(serviceInitializer);

            return new Result(await DeleteRequest(bigqueryService, input, connection, cancellationToken));
        }
        catch (Exception ex)
        {
            return ex.Handle(options);
        }
    }

    private static async Task<ServiceAccountCredential> GetServiceAccountCredential(Connection connection, CancellationToken cancellationToken)
    {
        var jsonCredentials = connection.ReadJsonMethod == ReadJsonMethods.File ? await File.ReadAllTextAsync(connection.CredentialsFilePath, cancellationToken) : connection.SecretJson;

        ServiceAccountCredential credential;
        using var stream = new MemoryStream(System.Text.Encoding.UTF8.GetBytes(jsonCredentials));
        credential = GoogleCredential.FromStream(stream)
                                     .CreateScoped(BigqueryService.Scope.Bigquery)
                                     .UnderlyingCredential as ServiceAccountCredential;

        return credential;
    }

    private static async Task<bool> DeleteRequest(BigqueryService service, Input input, Connection connection, CancellationToken cancellationToken)
    {
        switch (input.Resource)
        {
            case Resources.Dataset:
                await service.Datasets.Delete(connection.ProjectId, input.DatasetId).ExecuteAsync(cancellationToken);
                return true;
            case Resources.Job:
                await service.Jobs.Delete(connection.ProjectId, input.JobId).ExecuteAsync(cancellationToken);
                return true;
            case Resources.Model:
                await service.Models.Delete(connection.ProjectId, input.DatasetId, input.ModelId).ExecuteAsync(cancellationToken);
                return true;
            case Resources.Routine:
                await service.Routines.Delete(connection.ProjectId, input.DatasetId, input.RoutineId).ExecuteAsync(cancellationToken);
                return true;
            case Resources.Table:
                await service.Tables.Delete(connection.ProjectId, input.DatasetId, input.TableId).ExecuteAsync(cancellationToken);
                return true;
            default:
                throw new Exception("Resource not supported.");
        }
    }
}